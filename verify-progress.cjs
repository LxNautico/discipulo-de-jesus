const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(__dirname + '/app.js', 'utf8').split('const app=document.querySelector')[0];
let saved = JSON.stringify({completed:[0,2,5,5,99],notes:{0:'Criação',2:'Abraão',5:'Missão'}});
function load() {
  const ctx = vm.createContext({localStorage:{getItem:()=>saved,setItem:(_,s)=>{saved=s;}}});
  vm.runInContext(source,ctx);
  return {ctx,state:JSON.parse(vm.runInContext('JSON.stringify(state)',ctx))};
}
const first=load();
assert.deepEqual(first.state.completed,[0,5,19]);
assert.deepEqual(first.state.notes,{'0':'Criação','5':'Abraão','19':'Missão'});
assert.equal(first.state.schemaVersion,5);
assert.deepEqual(load().state,first.state);
assert.equal(vm.runInContext('lessons.length',first.ctx),20);
vm.runInContext('lessons.forEach(l=>{if(!l.answers[l.correct] || !l.practice || !l.explain)throw Error(l.title);})',first.ctx);
saved=JSON.stringify({schemaVersion:2,completed:[0,2,3,4],notes:{3:'Noé'}});
assert.deepEqual(load().state.completed,[0,2,3,4]);
assert.equal(load().state.notes[3],'Noé');
saved=JSON.stringify({schemaVersion:2,completed:[5,6,7,8],notes:{6:'Moisés',8:'Missão'}});
const second=load().state;
assert.deepEqual(second.completed,[5,9,18,19]);
assert.deepEqual(second.notes,{'9':'Moisés','19':'Missão'});
assert.deepEqual(load().state,second);
saved=JSON.stringify({schemaVersion:3,completed:[6,7,8],notes:{8:'José'}});
assert.deepEqual(load().state.completed,[6,7,8]);
assert.equal(load().state.notes[8],'José');
saved=JSON.stringify({schemaVersion:3,completed:[9,10,11],notes:{9:'Moisés',10:'Reino',11:'Missão'}});
const third=load().state;
assert.deepEqual(third.completed,[9,18,19]);
assert.deepEqual(third.notes,{'9':'Moisés','18':'Reino','19':'Missão'});
assert.deepEqual(load().state,third);
saved=JSON.stringify({schemaVersion:4,completed:[10,11,12,13],notes:{13:'Sinai'}});
assert.deepEqual(load().state.completed,[10,11,12,13]);
assert.equal(load().state.notes[13],'Sinai');
saved=JSON.stringify({schemaVersion:4,completed:[13,14,15],notes:{13:'Sinai',14:'Reino',15:'Missão'}});
const fourth=load().state;
assert.deepEqual(fourth.completed,[13,18,19]);
assert.deepEqual(fourth.notes,{'13':'Sinai','18':'Reino','19':'Missão'});
assert.deepEqual(load().state,fourth);
saved=JSON.stringify({schemaVersion:5,completed:[14,15,16,17],notes:{17:'Rute'}});
assert.deepEqual(load().state.completed,[14,15,16,17]);
assert.equal(load().state.notes[17],'Rute');
console.log('OK: 20 estudos, gabaritos, migração de quatro versões anteriores, notas e recarga.');
