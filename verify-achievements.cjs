const assert=require('node:assert/strict');
const {catalog,evaluate}=require('./achievement-rules.js');
const base={xp:0,journeyCompleted:0,moneyCompleted:0,hasReflection:false};
const date='2026-10-15T15:00:00.000Z';
assert.equal(new Set(catalog.map(b=>b.id)).size,catalog.length);
assert.deepEqual(evaluate(base,{},date).added,[]);
assert.deepEqual(evaluate({...base,xp:99},{},date).added,[]);
const first=evaluate({...base,xp:100},{},date);
assert.deepEqual(first.added,['xp-100']);
assert.deepEqual(evaluate({...base,xp:100},first.unlocked,'2026-10-16T15:00:00.000Z').added,[]);
assert.equal(evaluate({...base,xp:100},first.unlocked).unlocked['xp-100'],date);
const recovered=evaluate({...base,xp:1000,journeyCompleted:10,moneyCompleted:4,hasReflection:true},{},date);
assert.deepEqual(recovered.added,['xp-100','xp-500','xp-1000','first-reflection']);
const thematic=evaluate({...base,moneyCompleted:5},{},date);
assert.deepEqual(thematic.added,['topic-money']);
assert.equal(base.xp,0);
const all=evaluate({...base,xp:2000,journeyCompleted:20,moneyCompleted:5,hasReflection:true},{},date);
assert.equal(all.added.length,catalog.length);
assert.deepEqual(evaluate({...base,xp:2000,journeyCompleted:20,moneyCompleted:5,hasReflection:true},all.unlocked).added,[]);
assert.equal(evaluate(base,all.unlocked).unlocked['topic-money'],date);
const sanitized=evaluate(base,{'xp-100':'inválido','inexistente':date},date);
assert.deepEqual(sanitized.unlocked,{});
console.log('OK: limites de XP, recuperação retroativa, trilha, reflexão, datas preservadas e recompensas sem duplicação ou XP extra.');
